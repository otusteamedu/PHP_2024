#!/bin/bash

# Проверка, передан ли аргумент (имя файла)
if [ "$#" -ne 1 ]; then
    echo "Ошибка: необходимо указать имя файла." >&2
    exit 1
fi

# Проверка, что файл существует
if [ ! -f "$1" ]; then
    echo "Ошибка: файл '$1' не найден." >&2
    exit 1
fi

# Обработка файла для нахождения трех наиболее популярных городов
awk 'NR > 1 {print $3}' "$1" | sort | uniq -c | sort -nr | head -n 3

# awk 'NR > 1 {print \$3}' "\$1" — этот шаг используется для извлечения третьего столбца (городов) из таблицы, пропуская первую строку, содержащую заголовки.
# sort — сортирует названия городов в алфавитном порядке для следующего шага.
# uniq -c — подсчитывает количество вхождений каждого города в отсортированном списке.
# sort -nr — сортирует результаты по убыванию количества вхождений (число перед названием города).
# head -n 3 — выводит только три самых популярных города.