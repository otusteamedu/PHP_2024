#!/bin/bash

# Проверка, переданы ли два аргумента
if [ "$#" -ne 2 ]; then
    echo "Ошибка: необходимо передать два числа." >&2
    exit 1
fi

# Проверка, что оба аргумента — это числа (можно использовать регулярное выражение)
if ! [[ "$1" =~ ^-?[0-9]*\.?[0-9]+$ ]]; then
    echo "Ошибка: '$1' не является числом." >&2
    exit 1
fi

if ! [[ "$2" =~ ^-?[0-9]*\.?[0-9]+$ ]]; then
    echo "Ошибка: '$2' не является числом." >&2
    exit 1
fi

# Подсчет суммы
sum=$(echo "$1 + $2" | bc)

# Вывод результата
echo "Сумма: $sum"