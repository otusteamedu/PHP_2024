#!/bin/bash

# Проверяем, что предоставлено два аргумента
if [ "$#" -ne 2 ]; then
    echo "Ошибка: требуется ровно два аргумента" >&2
    echo "Использование: $0 число1 число2" >&2
    exit 1
fi

# Регулярное выражение для проверки чисел (включая отрицательные и десятичные)
regex='^[+-]?[0-9]+([.][0-9]+)?$'

# Проверяем первый аргумент
if ! [[ $1 =~ $regex ]]; then
    echo "Ошибка: '$1' не является числом" >&2
    exit 1
fi

# Проверяем второй аргумент
if ! [[ $2 =~ $regex ]]; then
    echo "Ошибка: '$2' не является числом" >&2
    exit 1
fi

# Вычисляем сумму с помощью bc для поддержки десятичных чисел
sum=$(awk "BEGIN {print $1 + $2}")

# Выводим результат
echo "$sum"

awk '{print $3}' users.txt | tail -n +2 | sort | uniq -c | sort -nr | head -3
